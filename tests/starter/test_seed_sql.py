"""시드 SQL 을 코드가 쓴다 (2026-11-07 알파 3×3 — 시작 코드가 수백 행 시드를 생략, GENERATED ALWAYS 에 id 직접 입력). 가상 데이터만."""

from __future__ import annotations

from typing import Any

from task_spec.nodes.starter.plan_contract import fill_hidden_defaults
from task_spec.schemas import HiddenPlan, TaskContract
from task_spec.starter.seed_sql import (
    default_value,
    render_seed_sql,
    schema_problems,
    table_columns,
)
from task_spec.starter.templates import load_template
from tests.starter.test_contract import _contract, _plan

JAVA = load_template("backend/java-spring-boot3-jpa")
SCHEMA = """CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(20) NOT NULL,
    CONSTRAINT ck CHECK (status IN ('READY', 'SHIPPED'))
);
CREATE TABLE order_history (id BIGINT PRIMARY KEY, order_id BIGINT);
"""


def _seeded(**over: Any) -> TaskContract:
    c = _contract()
    c["seed"] = [
        {
            "entity_id": "m1",
            "rows": 250,
            "groups": [
                {"first": 1, "last": 10, "values": {"status": "READY"}},
                {"first": 11, "last": 250, "values": {"status": "SHIPPED"}},
            ],
        },
        {"entity_id": "m2", "rows": 0},
    ]
    c.update(over)
    return TaskContract.model_validate(c)


def test_every_row_is_written_with_group_values_and_restart() -> None:
    f = render_seed_sql(_seeded(), JAVA.manifest, SCHEMA)
    assert f is not None and f.path == "src/main/resources/data.sql"
    sql = f.content
    assert sql.count("INSERT INTO orders (id, status) VALUES") == 3  # 100행씩
    assert "(1, 'READY')" in sql and "(10, 'READY')" in sql and "(11, 'SHIPPED')" in sql
    assert "(250, 'SHIPPED')" in sql and "(251," not in sql
    assert "ALTER TABLE orders ALTER COLUMN id RESTART WITH 251;" in sql  # identity 열
    assert "-- OrderHistory: 0행" in sql and "INSERT INTO order_history" not in sql


def test_no_restart_when_id_is_not_identity_and_required_fields_get_defaults() -> None:
    c = _contract()
    c["entities"][0]["fields"].append(
        {"name": "createdAt", "type": "datetime", "required": True, "refs": ["r1"]}
    )
    c["entities"][0]["fields"].append(
        {"name": "note", "type": "string", "required": False, "refs": ["r1"]}
    )
    c["seed"] = [
        {
            "entity_id": "m1",
            "rows": 2,
            "groups": [{"first": 1, "last": 2, "values": {"status": "READY"}}],
        }
    ]
    contract = TaskContract.model_validate(c)
    schema = (
        "CREATE TABLE orders (id BIGINT PRIMARY KEY, status VARCHAR(20), created_at TIMESTAMP);"
    )
    sql = render_seed_sql(contract, JAVA.manifest, schema).content  # type: ignore[union-attr]
    assert (
        "INSERT INTO orders (id, status, created_at) VALUES" in sql
    )  # 선택 필드 note 는 넣지 않음
    assert "(2, 'READY', '2026-01-01T00:00:00')" in sql and "RESTART" not in sql


def test_type_defaults() -> None:
    from task_spec.schemas.build import ContractField

    def f(t: str) -> ContractField:
        return ContractField(name="x", type=t, refs=["r1"])

    assert default_value(f("enum(READY|SHIPPED)"), 7) == "READY"
    assert default_value(f("long"), 7) == 7 and default_value(f("boolean"), 7) is False
    assert default_value(f("date"), 7) == "2026-01-01" and default_value(f("string"), 7) == "x-7"


def test_schema_cross_check() -> None:
    c = _seeded()
    assert schema_problems(SCHEMA, c, JAVA.manifest) == []
    bad = SCHEMA.replace("status VARCHAR(20) NOT NULL,", "state VARCHAR(20),").replace(
        "BY DEFAULT", "ALWAYS"
    )
    probs = schema_problems(bad, c, JAVA.manifest)
    assert any("시드 열이 없음: status" in p for p in probs)
    assert any("GENERATED ALWAYS" in p for p in probs)
    assert any("CREATE TABLE 이 없음" in p for p in schema_problems("", c, JAVA.manifest))
    cols = table_columns(
        "id BIGINT, name VARCHAR(10), PRIMARY KEY (id), CONSTRAINT c UNIQUE (name)"
    )
    assert set(cols) == {"id", "name"}


def test_hidden_defaults_fill_only_invisible_params() -> None:
    plan = HiddenPlan.model_validate(_plan(harness={"pool_size": 8, "concurrency": 32}))
    filled, notes = fill_hidden_defaults(plan, JAVA.manifest)
    assert filled.harness["bursts"] == 3 and notes == [
        "숨은 조절값 bursts 가 없어 템플릿 기본값 3 을 넣음"
    ]
    same, none = fill_hidden_defaults(filled, JAVA.manifest)
    assert same is filled and none == []
    # 보이는 값(풀 크기 등)은 채우지 않는다 — 명세에서 와야 한다
    bare = HiddenPlan.model_validate(_plan(harness={"concurrency": 32}))
    out, _ = fill_hidden_defaults(bare, JAVA.manifest)
    assert "pool_size" not in out.harness
